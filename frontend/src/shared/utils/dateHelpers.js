// Normalizes various date formats (DD/MM/YYYY, DD-MM-YYYY, ISO strings, Date objects) to YYYY-MM-DD.
export const formatDateForInput = (value) => {
  if (!value) return '';
  const str = String(value).trim();
  if (/^\d{4}-\d{2}-\d{2}$/.test(str)) {
    return str;
  }
  const ddmmyyyy = str.match(/^(\d{1,2})[\/\-](\d{1,2})[\/\-](\d{4})$/);
  if (ddmmyyyy) {
    const [, d, m, y] = ddmmyyyy;
    return `${y}-${m.padStart(2, '0')}-${d.padStart(2, '0')}`;
  }
  const date = new Date(str);
  if (Number.isNaN(date.getTime())) return '';
  const year = date.getFullYear();
  const month = String(date.getMonth() + 1).padStart(2, '0');
  const day = String(date.getDate()).padStart(2, '0');
  return `${year}-${month}-${day}`;
};

// Local-timezone YYYY-MM-DD (toISOString() is UTC and can be a day off in IST).
export const getTodayDateString = () => {
  const now = new Date();
  const pad = (n) => String(n).padStart(2, '0');
  return `${now.getFullYear()}-${pad(now.getMonth() + 1)}-${pad(now.getDate())}`;
};

export const isPastDateString = (value) => {
  if (!value) return false;
  const normalized = formatDateForInput(value);
  if (!normalized) return false;
  return normalized < getTodayDateString();
};

